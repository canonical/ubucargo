//! Generates and validates staged Debian source packages from resolved inputs.

use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use anyhow::{Context, Result, bail};
use debian_control::lossless::control::Control;
use tempfile::TempDir;

use crate::{
    cargo::read_package_identity,
    changelog::prepare_changelog,
    config::{get_staged_config_path, write_staged_config},
    debcargo,
    resolve::{ResolvedPackage, normalize_crate_name},
    source::filter_maintainer_patch_series,
    util::copy_tree,
};

/// Selects full packaging or preparation for maintainer patch porting.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum GenerationMode {
    /// Generate and reconcile the complete Debian packaging.
    Full,
    /// Prepare source and automatic patches without applying maintainer patches.
    Prepare,
}

/// Validated files and identities produced by final debcargo generation.
pub struct GeneratedPackage {
    /// Requested packaging workflow.
    pub mode: GenerationMode,
    /// Temporary directory containing all staged generation state.
    pub stage: TempDir,
    /// Staged source package tree.
    pub source: PathBuf,
    /// Staged Debian orig tarball.
    pub orig: PathBuf,
}

/// Generates and validates a staged source package using the resolved release and configuration.
pub fn generate_package(
    package: &ResolvedPackage,
    destination: &Path,
    keep_staging: bool,
    mode: GenerationMode,
    show_fixmes: bool,
) -> Result<GeneratedPackage> {
    let stage = tempfile::Builder::new()
        .disable_cleanup(keep_staging)
        .tempdir()
        .context("create package staging directory")?;
    if keep_staging {
        eprintln!("package staging directory: {}", stage.path().display());
    }
    // Isolate destination names from staging files and use them in debcargo's relative diagnostics.
    let output = stage.path().join("output");
    fs::create_dir(&output)?;
    let source = output.join(
        destination
            .file_name()
            .context("package destination has no name")?,
    );
    let overlay = stage.path().join("overlay");
    fs::create_dir(&overlay)?;
    let deferred_series = if mode == GenerationMode::Full
        && let Some(existing) = &package.existing
    {
        stage_maintainer_patches(
            &existing.root.join("debian/patches"),
            &overlay.join("patches"),
        )?
    } else {
        String::new()
    };
    write_staged_config(&package.config, stage.path())?;
    prepare_changelog(package, &overlay.join("changelog"), mode)?;
    run_debcargo(stage.path(), &source, package, show_fixmes)?;
    restore_deferred_series(&source.join("debian/patches"), &deferred_series)?;
    validate_debcargo_output(
        stage,
        source,
        &package.source_name,
        &package.upstream,
        &package.crate_selection.crate_name,
        &package.crate_selection.version,
        mode,
    )
}

/// Stages maintained patches, deferring series without patch entries until after generation.
fn stage_maintainer_patches(patches: &Path, staged_patches: &Path) -> Result<String> {
    let mut deferred_series = String::new();
    if !patches.is_dir() {
        return Ok(deferred_series);
    }
    fs::create_dir(staged_patches)?;
    for entry in fs::read_dir(patches)? {
        let entry = entry?;
        let name = entry.file_name();
        if name == "auto" {
            continue;
        }
        if name == "series" {
            let series = filter_maintainer_patch_series(&fs::read_to_string(entry.path())?);
            let has_patches = series.lines().any(|line| {
                let patch = line.split_whitespace().next().unwrap_or("");
                !patch.is_empty() && !patch.starts_with('#')
            });
            if has_patches {
                fs::write(staged_patches.join(&name), series)?;
            } else {
                // Debcargo runs quilt whenever series exists, even with only comments;
                // defer it because quilt reports an empty stack as a failure.
                deferred_series = series;
            }
        } else {
            copy_tree(&entry.path(), &staged_patches.join(&name))?;
        }
    }
    Ok(deferred_series)
}

/// Restores deferred series text after any automatic patches generated by debcargo.
fn restore_deferred_series(patches: &Path, deferred_series: &str) -> Result<()> {
    if deferred_series.is_empty() {
        return Ok(());
    }
    fs::create_dir_all(patches)?;
    let series_path = patches.join("series");
    let mut series = fs::read_to_string(&series_path).or_else(|error| {
        if error.kind() == std::io::ErrorKind::NotFound {
            Ok(String::new())
        } else {
            Err(error)
        }
    })?;
    series.push_str(deferred_series);
    fs::write(series_path, series)?;
    Ok(())
}

/// Runs final debcargo generation for one exact selected release.
fn run_debcargo(
    stage: &Path,
    source: &Path,
    package: &ResolvedPackage,
    show_fixmes: bool,
) -> Result<()> {
    let mut command = Command::new("debcargo");
    command
        .arg("package")
        .arg("--config")
        .arg(get_staged_config_path(stage))
        .arg("--directory")
        .arg(source)
        .arg("--no-overlay-write-back")
        .arg("--changelog-ready")
        .arg(&package.crate_selection.crate_name)
        .arg(&package.crate_selection.version)
        .current_dir(source.parent().unwrap());
    if package.config.resolved_crate_src_path.is_some() {
        // Local packaging needs a unique target directory: rust-lang/cargo#16683.
        command.env("CARGO_TARGET_DIR", stage.join("cargo-target"));
    } else {
        // Registry normalization uses the isolated extracted tree's target directory.
        command.env_remove("CARGO_TARGET_DIR");
    }
    debcargo::run_command(&mut command, "debcargo package", show_fixmes)
}

/// Validates staged source identity, Cargo identity, essential packaging, and orig naming.
fn validate_debcargo_output(
    stage: TempDir,
    source: PathBuf,
    expected_source: &str,
    expected_upstream: &str,
    requested_name: &str,
    requested_version: &str,
    mode: GenerationMode,
) -> Result<GeneratedPackage> {
    for path in [
        source.join("Cargo.toml"),
        source.join("debian/changelog"),
        source.join("debian/control"),
        source.join("debian/rules"),
        source.join("debian/source/format"),
    ] {
        if !path.is_file() {
            bail!("debcargo produced no {}", path.display());
        }
    }

    let package = read_package_identity(&source)?;
    if normalize_crate_name(requested_name) != normalize_crate_name(&package.name) {
        bail!(
            "debcargo selected crate {} instead of {requested_name}",
            package.name
        );
    }
    if package.version != requested_version {
        bail!(
            "debcargo selected {} {} instead of requested version {requested_version}",
            package.name,
            package.version
        );
    }

    let control = Control::from_file(source.join("debian/control"))
        .context("parse generated debian/control")?;
    let debian_source = control
        .source()
        .context("generated debian/control has no source paragraph")?
        .name()
        .context("generated debian/control has no Source field")?;
    if debian_source != expected_source {
        bail!("debcargo produced Debian source {debian_source}, expected {expected_source}");
    }
    if fs::read(source.join("debian/changelog"))?
        != fs::read(stage.path().join("overlay/changelog"))?
    {
        bail!("debcargo changed the prepared changelog despite --changelog-ready");
    }

    let orig = source
        .parent()
        .unwrap()
        .join(format!("{expected_source}_{expected_upstream}.orig.tar.gz"));
    if !orig.is_file() {
        bail!("debcargo produced no {}", orig.display());
    }
    Ok(GeneratedPackage {
        mode,
        stage,
        source,
        orig,
    })
}
